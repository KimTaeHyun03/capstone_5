import { test,expect } from '@playwright/test';

test.beforeEach(async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'점주 체험',exact:true}).click();
});
test('manual sale persists and duplicate CSV cannot partially save',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.getByLabel('결제번호',{exact:true}).fill('UI-ORDER');
  await page.getByLabel('메뉴',{exact:true}).selectOption('m1');
  await page.getByLabel('수량',{exact:true}).fill('2');
  await page.getByRole('button',{name:'판매 저장',exact:true}).click();
  await expect(page.getByRole('cell',{name:'UI-ORDER',exact:true})).toBeVisible();
  await page.reload();
  await expect(page.getByRole('cell',{name:'UI-ORDER',exact:true})).toBeVisible();
  const soldAt=await page.getByLabel('판매 일시 (한국 시간)',{exact:true}).inputValue();
  const csv=`payment_no,menu_id,sold_at,quantity,amount\nUI-NEW,m1,${soldAt},1,4500\nUI-ORDER,m1,${soldAt},1,4500\n`;
  await page.getByLabel('CSV 파일 선택').setInputFiles({name:'sales.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
  await expect(page.getByRole('alert')).toContainText('동일 결제번호');
  await expect(page.getByRole('cell',{name:'UI-NEW',exact:true})).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('ingredient, menu, recipe CRUD and updated costs survive refresh',async({page})=>{
  await page.goto('/#/owner/base/ingredient');
  await page.getByRole('button',{name:'재료 추가',exact:true}).click();
  await page.getByLabel('재료명').fill('테스트 재료');
  await page.getByLabel('사용 단위당 단가(원)').fill('100');
  await page.getByRole('button',{name:'저장',exact:true}).click();
  await expect(page.getByRole('row').filter({hasText:'테스트 재료'})).toBeVisible();
  await page.goto('/#/owner/base/menu');
  await page.getByRole('button',{name:'메뉴 추가',exact:true}).click();
  await page.getByLabel('메뉴명').fill('테스트 메뉴');
  await page.getByLabel('판매가(원)').fill('1000');
  await page.getByRole('button',{name:'저장',exact:true}).click();
  let row=page.getByRole('row').filter({hasText:'테스트 메뉴'});
  await row.getByRole('button',{name:'레시피 0개'}).click();
  await page.getByRole('button',{name:'재료 추가',exact:true}).click();
  await page.getByLabel('재료 1',{exact:true}).selectOption({label:'테스트 재료 (개)'});
  await page.getByLabel('소요량',{exact:true}).fill('2');
  await page.getByRole('button',{name:'저장',exact:true}).click();
  await expect(row).toContainText('200원');
  await page.reload();
  await expect(row).toContainText('200원');
  await page.goto('/#/owner/base/ingredient');
  row=page.getByRole('row').filter({hasText:'테스트 재료'});
  await row.getByRole('button',{name:'수정',exact:true}).click();
  await page.getByLabel('사용 단위당 단가(원)').fill('150');
  await page.getByRole('button',{name:'저장',exact:true}).click();
  await page.goto('/#/owner/base/menu');
  await expect(page.getByRole('row').filter({hasText:'테스트 메뉴'})).toContainText('300원');
  await page.goto('/#/owner/base/ingredient');
  await page.getByRole('row').filter({hasText:'테스트 재료'}).getByRole('button',{name:'삭제',exact:true}).click();
  await page.getByRole('button',{name:'삭제 확인',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('레시피에서 사용 중');
});
test('staff availability updates owner overview and zero availability remains submitted',async({page})=>{
  await page.goto('/#/staff/availability');
  const pressed=page.locator('.slot-btn[aria-pressed="true"]');
  while(await pressed.count())await pressed.first().click();
  await page.getByRole('button',{name:'가능시간 저장',exact:true}).click();
  await expect(page.locator('.toast-region')).toContainText('가능시간을 저장');
  await page.goto('/#/owner/work/availability');
  const row=page.getByRole('row').filter({hasText:'정윤수'});
  await expect(row).toContainText('불가');
  await expect(row).not.toContainText('미제출');
  await page.getByRole('button',{name:'다음 주',exact:true}).click();
  await expect(row).toContainText('미제출');
  await page.getByRole('button',{name:'이전 주',exact:true}).click();
  await expect(row).not.toContainText('미제출');
});
test('staff account validation, edit and delete in demo',async({page})=>{
  await page.goto('/#/owner/base/store');
  await page.getByRole('button',{name:'직원 등록',exact:true}).click();
  await page.getByRole('button',{name:'저장',exact:true}).click();
  await expect(page.getByRole('alert')).toContainText('이름');
  await page.locator('#edit-name').fill('테스트 직원');
  await page.getByLabel('초대 이메일').fill('new@example.test');
  await page.getByRole('button',{name:'저장',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'테스트 직원'});
  await expect(row).toContainText('초대됨');
  await expect(row.getByRole('button',{name:'이메일 초대'})).toBeDisabled();
  await row.getByRole('button',{name:'수정',exact:true}).click();
  await page.getByLabel('상태',{exact:true}).selectOption('활성');
  await page.getByRole('button',{name:'저장',exact:true}).click();
  await expect(row).toContainText('활성');
  await row.getByRole('button',{name:'삭제',exact:true}).click();
  await page.getByRole('button',{name:'삭제 확인',exact:true}).click();
  await expect(row).toHaveCount(0);
});
