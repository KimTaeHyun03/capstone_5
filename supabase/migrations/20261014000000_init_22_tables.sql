create table store (
    store_id                bigint generated by default as identity primary key,
    store_name              varchar(100) not null,
    address                 varchar(255),
    phone                   varchar(20),
    open_time               time,
    close_time              time,
    closed_days             varchar(50)
);

create table user_account (
    user_id                 bigint generated by default as identity primary key,
    store_id                bigint not null,
    login_id                varchar(50) not null,
    password_hash           varchar(255) not null,
    name                    varchar(50) not null,
    role                    varchar(20) not null,
    hourly_wage             integer,
    max_weekly_hours        numeric(4,1),
    preferred_weekly_hours  numeric(4,1),
    phone                   varchar(20),
    status                  varchar(20) not null,
    unique (login_id)
);

create table menu (
    menu_id                 bigint generated by default as identity primary key,
    store_id                bigint not null,
    menu_name               varchar(100) not null,
    category                varchar(50),
    price                   integer not null,
    is_on_sale              boolean not null,
    recipe_status           varchar(20),
    cost                    integer,
    cost_rate               numeric(5,2)
);

create table ingredient (
    ingredient_id           bigint generated by default as identity primary key,
    store_id                bigint not null,
    ingredient_name         varchar(100) not null,
    use_unit                varchar(20) not null,
    order_unit              varchar(20) not null,
    conversion_rate         numeric(10,3),
    unit_price              integer,
    min_stock               numeric(10,2)
);

create table recipe (
    recipe_id               bigint generated by default as identity primary key,
    menu_id                 bigint not null,
    ingredient_id           bigint not null,
    qty_per_menu            numeric(10,3) not null,
    unique (menu_id, ingredient_id)
);

create table sale (
    sale_id                 bigint generated by default as identity primary key,
    payment_no              varchar(30) not null,
    menu_id                 bigint not null,
    sold_at                 timestamptz not null,
    quantity                integer not null,
    amount                  integer not null
);

create table sales_summary (
    summary_id              bigint generated by default as identity primary key,
    store_id                bigint not null,
    base_date               date not null,
    day_of_week             smallint not null,
    time_slot               smallint not null,
    sales_amount            integer not null,
    order_count             integer not null,
    is_confirmed            boolean not null,
    unique (store_id, base_date, time_slot)
);

create table sales_forecast (
    forecast_id             bigint generated by default as identity primary key,
    store_id                bigint not null,
    target_week             date not null,
    day_of_week             smallint not null,
    time_slot               smallint not null,
    forecast_amount         integer not null,
    is_peak                 boolean not null,
    required_staff          integer,
    needs_more_staff        boolean
);

create table availability (
    availability_id         bigint generated by default as identity primary key,
    user_id                 bigint not null,
    day_of_week             smallint not null,
    start_time              time not null,
    end_time                time not null,
    registered_at           timestamptz not null
);

create table work_schedule (
    schedule_id             bigint generated by default as identity primary key,
    store_id                bigint not null,
    target_week             date not null,
    status                  varchar(20) not null,
    created_at              timestamptz not null,
    confirmed_by            bigint,
    confirmed_at            timestamptz,
    is_published            boolean not null,
    published_at            timestamptz,
    unique (store_id, target_week)
);

create table shift_assignment (
    assignment_id           bigint generated by default as identity primary key,
    schedule_id             bigint not null,
    user_id                 bigint not null,
    work_date               date not null,
    planned_start           time not null,
    planned_end             time not null,
    is_modified             boolean not null,
    modified_by             bigint,
    has_warning             boolean not null
);

create table attendance (
    attendance_id           bigint generated by default as identity primary key,
    user_id                 bigint not null,
    assignment_id           bigint,
    clock_in                timestamptz not null,
    clock_out               timestamptz,
    actual_hours            numeric(5,2),
    status                  varchar(20)
);

create table payroll (
    payroll_id              bigint generated by default as identity primary key,
    user_id                 bigint not null,
    period_start            date not null,
    period_end              date not null,
    total_hours             numeric(5,2) not null,
    applied_wage            integer not null,
    base_pay                integer not null,
    is_holiday_pay_target   boolean not null,
    holiday_pay             integer,
    total_pay               integer not null,
    calculated_at           timestamptz not null,
    unique (user_id, period_start)
);

create table inventory (
    inventory_id            bigint generated by default as identity primary key,
    ingredient_id           bigint not null,
    current_qty             numeric(10,2) not null,
    updated_at              timestamptz not null,
    is_short                boolean not null,
    unique (ingredient_id)
);

create table shortage_report (
    report_id               bigint generated by default as identity primary key,
    ingredient_id           bigint not null,
    reporter_id             bigint not null,
    shortage_level          varchar(20),
    memo                    varchar(255),
    reported_at             timestamptz not null,
    status                  varchar(20) not null
);

create table notification (
    notification_id         bigint generated by default as identity primary key,
    recipient_id            bigint not null,
    report_id               bigint,
    type                    varchar(30) not null,
    source                  varchar(20) not null,
    content                 varchar(500),
    sent_at                 timestamptz not null,
    is_read                 boolean not null
);

create table forecast_error (
    error_id                bigint generated by default as identity primary key,
    ingredient_id           bigint not null,
    period_start            date not null,
    period_end              date not null,
    opening_stock           numeric(10,2) not null,
    closing_stock           numeric(10,2) not null,
    actual_usage            numeric(10,2) not null,
    forecast_usage          numeric(10,2) not null,
    error_qty               numeric(10,2) not null,
    error_rate              numeric(6,2) not null,
    waste_qty               numeric(10,2)
);

create table correction_coefficient (
    coefficient_id          bigint generated by default as identity primary key,
    ingredient_id           bigint not null,
    error_id                bigint,
    previous_value          numeric(6,3),
    coefficient             numeric(6,3) not null,
    qty_before              numeric(10,2),
    qty_after               numeric(10,2),
    effective_from          date not null,
    applied_at              timestamptz not null
);

create table order_recommendation (
    recommendation_id       bigint generated by default as identity primary key,
    ingredient_id           bigint not null,
    coefficient_id          bigint,
    period_start            date not null,
    period_end              date not null,
    forecast_usage          numeric(10,2) not null,
    stock_at_calc           numeric(10,2) not null,
    recommended_qty         numeric(10,2) not null,
    estimated_cost          integer,
    calculated_at           timestamptz not null
);

create table purchase_order (
    order_id                bigint generated by default as identity primary key,
    ingredient_id           bigint not null,
    recommendation_id       bigint,
    ordered_by              bigint not null,
    order_qty               numeric(10,2) not null,
    is_adjusted             boolean not null,
    status                  varchar(20) not null,
    ordered_at              timestamptz not null
);

create table receipt (
    receipt_id              bigint generated by default as identity primary key,
    order_id                bigint not null,
    handled_by              bigint not null,
    received_qty            numeric(10,2) not null,
    diff_qty                numeric(10,2),
    diff_reason             varchar(255),
    received_at             timestamptz not null
);

create table inventory_change (
    change_id               bigint generated by default as identity primary key,
    ingredient_id           bigint not null,
    change_type             varchar(20) not null,
    sale_id                 bigint,
    receipt_id              bigint,
    change_qty              numeric(10,2) not null,
    reason                  varchar(255),
    handled_by              bigint,
    changed_at              timestamptz not null
);

