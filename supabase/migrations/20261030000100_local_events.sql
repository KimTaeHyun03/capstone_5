create or replace function public.set_store_location(p_lat numeric, p_lon numeric, p_radius integer default 1000)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if app.my_store_id() is null or not app.is_owner() then raise exception '점주만 매장 위치를 바꿀 수 있습니다' using errcode = '42501'; end if;
  if p_lat not between 33 and 39 or p_lon not between 124 and 132 then raise exception '국내 좌표를 입력하세요'; end if;
  update public.store set latitude = p_lat, longitude = p_lon, event_radius_m = coalesce(p_radius, event_radius_m) where store_id = app.my_store_id();
  -- 거리 다시 계산
  update public.local_event set distance_m = app.haversine_m(p_lat, p_lon, latitude, longitude)
   where store_id = app.my_store_id() and latitude is not null;
end $$;

create or replace function public.save_local_event(p_event jsonb)
returns bigint language plpgsql security definer set search_path = '' as $$
declare
  v_store bigint := app.my_store_id();
  v_id    bigint := nullif(p_event ->> 'event_id', '')::bigint;
  v_s     public.store%rowtype;
  v_lat   numeric := nullif(p_event ->> 'latitude', '')::numeric;
  v_lon   numeric := nullif(p_event ->> 'longitude', '')::numeric;
  v_dist  integer;
  v_title text := btrim(coalesce(p_event ->> 'title', ''));
begin
  if v_store is null or not app.is_owner() then raise exception '점주만 행사를 등록할 수 있습니다' using errcode = '42501'; end if;
  if v_title = '' or length(v_title) > 200 then raise exception '행사 이름은 1~200자로 입력하세요'; end if;
  select * into v_s from public.store where store_id = v_store;
  if v_lat is not null and v_lon is not null and v_s.latitude is not null then
    v_dist := app.haversine_m(v_s.latitude, v_s.longitude, v_lat, v_lon);
  end if;
  if v_id is null then
    insert into public.local_event (store_id, source, title, start_date, end_date, start_time, end_time, latitude, longitude, distance_m, scale, uplift_rate, status)
    values (v_store, 'manual', v_title, (p_event ->> 'start_date')::date, (p_event ->> 'end_date')::date,
            nullif(p_event ->> 'start_time', '')::time, nullif(p_event ->> 'end_time', '')::time, v_lat, v_lon, v_dist,
            coalesce(nullif(p_event ->> 'scale', ''), 'medium'), nullif(p_event ->> 'uplift_rate', '')::numeric,
            coalesce(nullif(p_event ->> 'status', ''), '반영'))
    returning event_id into v_id;
  else
    update public.local_event
       set title = v_title, start_date = (p_event ->> 'start_date')::date, end_date = (p_event ->> 'end_date')::date,
           start_time = nullif(p_event ->> 'start_time', '')::time, end_time = nullif(p_event ->> 'end_time', '')::time,
           scale = coalesce(nullif(p_event ->> 'scale', ''), scale), uplift_rate = nullif(p_event ->> 'uplift_rate', '')::numeric,
           status = coalesce(nullif(p_event ->> 'status', ''), status),
           latitude = coalesce(v_lat, latitude), longitude = coalesce(v_lon, longitude), distance_m = coalesce(v_dist, distance_m)
     where event_id = v_id and store_id = v_store;
    if not found then raise exception '행사를 찾을 수 없습니다'; end if;
  end if;
  return v_id;
end $$;

create or replace function public.set_local_event_status(p_event bigint, p_status text)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if app.my_store_id() is null or not app.is_owner() then raise exception '점주만 행사를 바꿀 수 있습니다' using errcode = '42501'; end if;
  if p_status not in ('제안', '반영', '제외') then raise exception '상태는 제안·반영·제외 중 하나여야 합니다'; end if;
  update public.local_event set status = p_status where event_id = p_event and store_id = app.my_store_id();
  if not found then raise exception '행사를 찾을 수 없습니다'; end if;
end $$;

create or replace function public.delete_local_event(p_event bigint)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if app.my_store_id() is null or not app.is_owner() then raise exception '점주만 행사를 지울 수 있습니다' using errcode = '42501'; end if;
  delete from public.local_event where event_id = p_event and store_id = app.my_store_id();
end $$;

-- 행사를 예측·발주에 바로 다시 반영한다(점주 화면의 '예측 다시 계산').
create or replace function public.refresh_forecast_with_events(p_target_week date default null)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare v_week date; v_slots integer; v_rec integer;
begin
  if app.my_store_id() is null or not app.is_owner() then raise exception '점주만 실행할 수 있습니다' using errcode = '42501'; end if;
  v_week := date_trunc('week', coalesce(p_target_week, (now() at time zone 'Asia/Seoul')::date + 7))::date;
  v_slots := app.generate_sales_forecast_for(app.my_store_id(), v_week);
  v_rec := public.calculate_order_recommendations_impl(v_week);
  return jsonb_build_object('target_week', v_week, 'forecast_slots', v_slots, 'recommendations', v_rec);
end $$;

-- ---------------------------------------------------------------------
-- 7. 공공 API 수집 결과 저장 (Edge Function 이 service_role 로만 호출)
-- ---------------------------------------------------------------------
create or replace function public.upsert_synced_events(p_store bigint, p_events jsonb)
returns integer language plpgsql security definer set search_path = '' as $$
declare e jsonb; v_s public.store%rowtype; v_new integer := 0; v_dist integer; v_id bigint;
begin
  select * into v_s from public.store where store_id = p_store;
  if not found then raise exception '매장을 찾을 수 없습니다'; end if;
  for e in select * from jsonb_array_elements(coalesce(p_events, '[]'::jsonb)) loop
    v_dist := case when v_s.latitude is not null and nullif(e ->> 'latitude', '') is not null
                   then app.haversine_m(v_s.latitude, v_s.longitude, (e ->> 'latitude')::numeric, (e ->> 'longitude')::numeric) end;
    if v_dist is not null and v_dist > v_s.event_radius_m then continue; end if;
    insert into public.local_event (store_id, source, external_id, title, start_date, end_date, start_time, end_time, latitude, longitude, distance_m, scale)
    values (p_store, 'api', e ->> 'external_id', left(e ->> 'title', 200), (e ->> 'start_date')::date, (e ->> 'end_date')::date,
            nullif(e ->> 'start_time', '')::time, nullif(e ->> 'end_time', '')::time,
            nullif(e ->> 'latitude', '')::numeric, nullif(e ->> 'longitude', '')::numeric, v_dist, 'medium')
    on conflict (store_id, external_id) do update
      set title = excluded.title, start_date = excluded.start_date, end_date = excluded.end_date,
          start_time = excluded.start_time, end_time = excluded.end_time,
          latitude = excluded.latitude, longitude = excluded.longitude, distance_m = excluded.distance_m
    returning event_id into v_id;
    if (select created_at >= now() - interval '1 minute' from public.local_event where event_id = v_id) then v_new := v_new + 1; end if;
  end loop;
  if v_new > 0 then
    insert into public.notification (recipient_id, report_id, type, source, content, sent_at, is_read)
    select o.user_id, null, '주변 행사 제안', '자동 감지',
           format('매장 주변에서 새 행사 %s건을 찾았습니다. 행사 관리에서 확인하고 반영하세요.', v_new), now(), false
      from public.user_account o where o.store_id = p_store and o.role = '점주' and o.status = '활성';
  end if;
  return v_new;
end $$;

