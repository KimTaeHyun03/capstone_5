-- =====================================================================
-- 주변 행사 반영 매출 예측·발주 (1번 이벤트 E4 확장, 시험 단계)
-- 매장 반경 안의 행사가 '반영' 상태이면 그 날짜·시간대의 예측을 올리고, 권장 발주량도 같은 비율로 늘린다.
--
-- ■ 테이블 추가 예외: 팀 결정으로 local_event 1개를 추가한다(22 → 23개). 그 외 테이블은 만들지 않는다.
-- ■ 되돌리기 쉽게 만든 방식
--   - 기존 함수를 덮어쓰지 않고 이름만 바꿔 두고(…_pre_events) 그 위에 감싸는 함수를 새로 만든다.
--   - 기존 테이블에는 컬럼만 더한다(store 3개, sales_forecast 2개).
--   - 되돌리려면 supabase/handoff/rollback_local_events.sql 을 SQL Editor 에서 실행한다.
-- ■ 발주 이중 계산 방지: 기존 발주 계산은 예측 매출 비율(최대 ±20%)을 쓴다. 행사 가산이 거기에 섞이지 않도록
--   감싸는 함수가 계산 동안만 예측을 행사 가산 전 금액(base_amount)으로 되돌렸다가, 계산 뒤에 행사 가산을 따로 곱한다.
-- ■ 기본 가산표(임의의 시작값): 300m 이내 small 10%·medium 20%·large 30% / 300m~반경 small 5%·medium 10%·large 15% / 반경 밖 0
--   같은 매장·같은 규모의 지난 행사 실측(actual_ratio)이 2건 이상이면 그 평균을 쓴다. 한 날짜·시간대 합산 상한 30%.
-- =====================================================================

