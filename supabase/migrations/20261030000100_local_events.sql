  add column event_uplift numeric(4,3) not null default 0,   -- 이 칸에 적용된 행사 가산율
  add column base_amount  integer;                           -- 행사 가산 전 금액(null = 가산 없음)

-- ---------------------------------------------------------------------
-- 2. 행사 테이블
-- ---------------------------------------------------------------------
create table local_event (
    event_id        bigint generated by default as identity primary key,
    store_id        bigint not null references store (store_id) on delete cascade,
    source          varchar(10) not null check (source in ('api', 'manual')),
    external_id     varchar(100),
    title           varchar(200) not null,
    start_date      date not null,
    end_date        date not null,
    start_time      time,
    end_time        time,
    latitude        numeric(9,6),
    longitude       numeric(9,6),
    distance_m      integer,
    scale           varchar(10) not null default 'medium' check (scale in ('small', 'medium', 'large')),
    uplift_rate     numeric(4,3) check (uplift_rate between 0 and 0.3),   -- null = 기본 가산표
    status          varchar(10) not null default '제안' check (status in ('제안', '반영', '제외')),
    actual_ratio    numeric(5,3),                                          -- 행사 후 실제 ÷ 가산 전 예측
    created_at      timestamptz not null default now(),
    check (end_date >= start_date),
    unique (store_id, external_id)
);
comment on table local_event is '매장 주변 행사. 공공 API 또는 점주 입력. 반영 상태인 행사만 매출 예측에 들어간다';
create index local_event_store_date on local_event (store_id, start_date, end_date);

alter table local_event enable row level security;
create policy "member read local_event" on local_event for select to authenticated
  using (store_id = app.my_store_id());
revoke all on local_event from anon;
revoke insert, update, delete on local_event from authenticated;   -- 쓰기는 아래 함수로만

-- ---------------------------------------------------------------------
-- 3. 계산 함수
-- ---------------------------------------------------------------------
create or replace function app.haversine_m(lat1 numeric, lon1 numeric, lat2 numeric, lon2 numeric)
returns integer language sql immutable set search_path = '' as $$
  select round(6371000 * 2 * asin(sqrt(
    power(sin(radians(lat2 - lat1) / 2), 2) +
    cos(radians(lat1)) * cos(radians(lat2)) * power(sin(radians(lon2 - lon1) / 2), 2))))::integer
$$;

-- 기본 가산율: 학습값(그 매장·같은 규모의 지난 행사 평균) > 기본표
create or replace function app.default_uplift(p_store bigint, p_scale text, p_distance integer, p_radius integer)
returns numeric language plpgsql stable security definer set search_path = '' as $$
declare v_learn numeric; v_n integer; v_near boolean := coalesce(p_distance, 0) <= 300;
begin
  if p_distance is not null and p_distance > p_radius then return 0; end if;
  select avg(actual_ratio - 1), count(*) into v_learn, v_n
    from public.local_event
   where store_id = p_store and scale = p_scale and actual_ratio is not null;
  if v_n >= 2 then return round(least(0.3, greatest(0, v_learn)), 3); end if;
  return case p_scale
    when 'small'  then case when v_near then 0.10 else 0.05 end
    when 'medium' then case when v_near then 0.20 else 0.10 end
    else               case when v_near then 0.30 else 0.15 end end;
end $$;

-- 대상 주(월요일 시작)의 (요일, 시간대)별 행사 가산율. 반영 상태인 행사만, 합산 후 상한 30%
create or replace function app.event_uplift_slots(p_store bigint, p_week date)
returns table (day_of_week smallint, time_slot smallint, uplift numeric, event_id bigint)
language sql stable security definer set search_path = '' as $$
  with ev as (
    select e.event_id, d::date as day,
           coalesce(e.uplift_rate, app.default_uplift(e.store_id, e.scale, e.distance_m, s.event_radius_m)) as rate,
           extract(hour from e.start_time)::integer as h1,
           case when e.end_time is null then null
                else extract(hour from e.end_time)::integer + (extract(minute from e.end_time) > 0)::integer end as h2
      from public.local_event e
      join public.store s using (store_id)
      cross join lateral generate_series(greatest(e.start_date, p_week), least(e.end_date, p_week + 6), interval '1 day') d
     where e.store_id = p_store and e.status = '반영'
  ), slot as (
    select ev.event_id, ev.day, ev.rate, h as hr
      from ev, generate_series(0, 23) h
     where (ev.h1 is null or h >= ev.h1) and (ev.h2 is null or h < ev.h2)
  )
  select (extract(isodow from day) - 1)::smallint, hr::smallint,
         least(0.3, sum(rate))::numeric, (array_agg(event_id order by rate desc))[1]
    from slot group by day, hr
$$;

-- 행사 후 실측: 끝난 행사의 실제 매출 ÷ 가산 전 예측
create or replace function app.update_event_actuals(p_store bigint)
returns integer language plpgsql security definer set search_path = '' as $$
declare r record; v_n integer := 0; v_actual numeric; v_base numeric;
begin
  for r in select * from public.local_event
            where store_id = p_store and status = '반영' and actual_ratio is null
              and end_date < (now() at time zone 'Asia/Seoul')::date loop
    select coalesce(sum(s.sales_amount), 0), coalesce(sum(f.base_amount), 0) into v_actual, v_base
      from public.sales_summary s
      join public.sales_forecast f on f.store_id = s.store_id and f.day_of_week = s.day_of_week and f.time_slot = s.time_slot
                                  and f.target_week = date_trunc('week', s.base_date)::date and f.base_amount is not null
     where s.store_id = p_store and s.is_confirmed and s.base_date between r.start_date and r.end_date
       and (r.start_time is null or s.time_slot >= extract(hour from r.start_time))
       and (r.end_time   is null or s.time_slot <  extract(hour from r.end_time) + (extract(minute from r.end_time) > 0)::integer);
    if v_base > 0 and v_actual > 0 then
      update public.local_event set actual_ratio = round(least(3, v_actual / v_base), 3) where event_id = r.event_id;
      v_n := v_n + 1;
    end if;
  end loop;
  return v_n;
end $$;

-- ---------------------------------------------------------------------
-- 4. 예측 생성에 행사 가산 붙이기 (기존 함수는 이름만 바꿔 둔다)
-- ---------------------------------------------------------------------
alter function app.generate_sales_forecast_for(bigint, date, integer) rename to generate_sales_forecast_for_pre_events;

create or replace function app.generate_sales_forecast_for(p_store bigint, p_target_week date default null, p_weeks integer default 4)
returns integer language plpgsql security definer set search_path = '' as $$
declare v_target date; v_count integer; v_ev integer;
begin
  perform app.update_event_actuals(p_store);
  v_count := app.generate_sales_forecast_for_pre_events(p_store, p_target_week, p_weeks);
  v_target := date_trunc('week', coalesce(p_target_week, (now() at time zone 'Asia/Seoul')::date + 7))::date;

  with u as (select * from app.event_uplift_slots(p_store, v_target) where uplift > 0)
  update public.sales_forecast f
     set base_amount = f.forecast_amount,
         event_uplift = u.uplift,
         forecast_amount = (round(f.forecast_amount * (1 + u.uplift) / 1000) * 1000)::integer,
         required_staff = app.required_staff((round(f.forecast_amount * (1 + u.uplift) / 1000) * 1000)::integer),
         is_peak = app.required_staff((round(f.forecast_amount * (1 + u.uplift) / 1000) * 1000)::integer) = 3,
         needs_more_staff = f.needs_more_staff
           or app.required_staff((round(f.forecast_amount * (1 + u.uplift) / 1000) * 1000)::integer) > f.required_staff
    from u
   where f.store_id = p_store and f.target_week = v_target
     and f.day_of_week = u.day_of_week and f.time_slot = u.time_slot;
  get diagnostics v_ev = row_count;

  if v_ev > 0 then
    insert into public.notification (recipient_id, report_id, type, source, content, sent_at, is_read)
    select o.user_id, null, '주변 행사 반영', '자동 감지',
           format('%s 주 예측에 주변 행사가 반영된 시간대가 %s개 있습니다. 권장 발주량도 함께 늘어납니다.', to_char(v_target, 'FMMM.DD'), v_ev),
           now(), false
      from public.user_account o
     where o.store_id = p_store and o.role = '점주' and o.status = '활성'
       and not exists (select 1 from public.notification n where n.recipient_id = o.user_id and n.type = '주변 행사 반영'
                          and n.content like to_char(v_target, 'FMMM.DD') || ' 주 %');
  end if;
  return v_count;
end $$;
revoke all on function app.generate_sales_forecast_for(bigint, date, integer) from public, anon, authenticated;
revoke all on function app.generate_sales_forecast_for_pre_events(bigint, date, integer) from public, anon, authenticated;

-- ---------------------------------------------------------------------
-- 5. 권장 발주량에 행사 가산 붙이기
-- ---------------------------------------------------------------------
-- 발주 수량: 기존 계산식(예상 소진 × 보정 계수 − 재고, 발주 단위 올림)과 같다
create or replace function app.event_order_qty(p_use numeric, p_factor numeric, p_stock numeric, p_conv numeric)
returns numeric language sql immutable set search_path = '' as $$
  select case when p_use * p_factor - p_stock <= 0 then 0
              else ceil((p_use * p_factor - p_stock) / coalesce(nullif(p_conv, 0), 1)) * coalesce(nullif(p_conv, 0), 1) end
$$;

alter function public.calculate_order_recommendations_impl(date) rename to calculate_order_recommendations_impl_pre_events;

create or replace function public.calculate_order_recommendations_impl(p_period_start date default null)
returns integer language plpgsql security definer set search_path = public set timezone = 'Asia/Seoul' as $$
declare
  v_store bigint := app.my_store_id();   -- null = 시스템 호출: 모든 매장
  v_start date := coalesce(p_period_start, (date_trunc('week', current_date) + interval '7 days')::date);
  v_n     integer;
  s       record;
begin
  -- 1) 기존 계산이 예측 비율(±20%)에 행사 가산을 섞어 쓰지 않도록, 계산 동안만 가산 전 금액으로 되돌린다.
  update sales_forecast set forecast_amount = base_amount
   where base_amount is not null and target_week = v_start and (v_store is null or store_id = v_store);

  v_n := calculate_order_recommendations_impl_pre_events(p_period_start);

  -- 2) 예측을 행사 가산 후 금액으로 복원한다. 가산 후 금액은 base_amount 와 event_uplift 로 다시 구한다.
  update sales_forecast set forecast_amount = (round(base_amount * (1 + event_uplift) / 1000) * 1000)::integer
   where base_amount is not null and target_week = v_start and (v_store is null or store_id = v_store);

  -- 3) 매장별 행사 가산(매출 가중 평균)을 방금 계산한 권장 발주량에 따로 곱한다.
  for s in
    select f.store_id, sum(f.forecast_amount)::numeric / nullif(sum(coalesce(f.base_amount, f.forecast_amount)), 0) - 1 as ev
      from sales_forecast f
     where f.target_week = v_start and (v_store is null or f.store_id = v_store)
     group by f.store_id
    having sum(f.forecast_amount) > sum(coalesce(f.base_amount, f.forecast_amount))
  loop
    update order_recommendation r
       set forecast_usage = round(r.forecast_usage * (1 + s.ev), 2),
           recommended_qty = app.event_order_qty(r.forecast_usage * (1 + s.ev),
             coalesce((select c.coefficient from correction_coefficient c where c.coefficient_id = r.coefficient_id), 1),
             r.stock_at_calc, i.conversion_rate),
           estimated_cost = round(app.event_order_qty(r.forecast_usage * (1 + s.ev),
             coalesce((select c.coefficient from correction_coefficient c where c.coefficient_id = r.coefficient_id), 1),
             r.stock_at_calc, i.conversion_rate) * coalesce(i.unit_price, 0))
      from ingredient i
     where i.ingredient_id = r.ingredient_id and i.store_id = s.store_id
       and r.period_start = v_start and r.calculated_at = now();
  end loop;
  return v_n;
end $$;
revoke all on function public.calculate_order_recommendations_impl(date) from public, anon, authenticated;
revoke all on function public.calculate_order_recommendations_impl_pre_events(date) from public, anon, authenticated;

